// Writes docs/design/07-critique-v2.md from critique-data.mjs.   node docs/tools/generate-critique.mjs
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CRITERIA, SCREENS } from './critique-data.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const avg = (rows) => (rows.flat().reduce((a, b) => a + b, 0) / rows.flat().length).toFixed(1);
const min = (rows) => Math.min(...rows.flat());
const hasAfter = SCREENS.every((s) => s.after);

const head = `| Screen | Width | ${CRITERIA.join(' | ')} | Lowest |\n|---|---|${CRITERIA.map(() => '---:').join('|')}|---:|`;
const row = (s, scores, width) => `| ${width === 1280 ? `**${s.name}**` : ''} | ${width} | ${scores.join(' | ')} | ${Math.min(...scores)} |`;
const table = (key) => [head, ...SCREENS.flatMap((s) => [row(s, s[key][0], 1280), row(s, s[key][1], 360)])].join('\n');

const perCriterion = (key) => CRITERIA.map((c, i) => {
  const values = SCREENS.flatMap((s) => [s[key][0][i], s[key][1][i]]);
  return `| ${c} | ${(values.reduce((a, b) => a + b, 0) / values.length).toFixed(1)} | ${Math.min(...values)} |`;
}).join('\n');

let md = `# Design critique v2 (Batch 4, Part 2)

> Generated by \`docs/tools/generate-critique.mjs\` from \`docs/tools/critique-data.mjs\`. Do not edit by hand.

**What this is.** The team's feedback after Batch 3 was: *"The design is still nothing special. Improve
and refine it a lot."* Before changing anything, every one of the 28 screens from \`npm run screenshots\`
was looked at in light mode at 1280 px and 360 px (English) and scored from 1 to 10 on ten criteria.

**Honest limits.** The scores are Claude Code's own judgement of the screenshots against the rubric
below. They are not a user test and not an expert panel; the team should look at the before/after pairs
in \`docs/design/screenshots/v3/\` and disagree where they see it differently. "Motion" cannot be seen in
a still image: it is scored from how the screen behaves in the browser (hover, focus, transitions,
loading), with reduced motion respected. "Layout" is the layout at that width; in the 360 px row it is the
"mobile layout" criterion of the prompt.

## Rubric

| Score | Meaning |
|---|---|
| 1-3 | Missing or broken (for example no imagery at all, a table cut off, text hard to read). |
| 4-5 | Present but generic or uneven: works, nobody would remember it. |
| 6-7 | Solid and consistent, but plain: a tidy student project. |
| 8 | Good: clear intent, few rough edges. |
| 9 | Professional: comparable in care to well-known products (Stripe, Linear, Airbnb, Apple, Material 3), without copying them. |
| 10 | Exceptional: nothing to improve at this size. |

| Criterion | What is judged |
|---|---|
| Hierarchy | Is there one clear first thing to look at, then a second, then the rest? One main action per screen? |
| Type | Scale, weights, line length, line height, tracking of display text, numbers, Urdu line height. |
| Spacing | An 8 px rhythm; related things close, unrelated things apart; no dead areas. |
| Colour | Emerald for trust and actions, saffron as one accent, calm neutrals; meaning never by colour alone. |
| Imagery | Illustrations that explain or welcome, in one style. No stock photos of people. |
| Depth | Layered surfaces, soft multi-layer shadows, fewer borders, tasteful texture. |
| Consistency | The same component looks and behaves the same everywhere. |
| Motion | Meaningful transitions and feedback; nothing moves with reduced motion. |
| Microcopy | Short, warm, specific words; errors that say what to do. |
| Layout | Use of the width: grids, alignment, nothing cut off, comfortable touch targets at 360 px. |

## Before: Batch 3 design (commit \`253a5af\`)

Average **${avg(SCREENS.map((s) => s.before.flat()))}**, lowest single score **${min(SCREENS.map((s) => s.before.flat()))}**.

${table('before')}

| Criterion | Average before | Lowest before |
|---|---:|---:|
${perCriterion('before')}

### The three biggest problems of each screen

${SCREENS.map((s) => `**${s.name}** (\`${s.id}\`)\n\n${s.problems.map((p, i) => `${i + 1}. ${p}`).join('\n')}`).join('\n\n')}

### The same problems, grouped (what the redesign must fix)

1. **Imagery is almost absent** (average ${perCriterion('before').split('\n')[4].split('|')[2].trim()}): one hero drawing and icons in tiles. Needed: one in-house
   illustration system (trades, empty states, onboarding steps, 404).
2. **Everything is a white card with a 1 px border.** No layering, no texture, no elevation levels.
3. **Short pages float above a heavy footer** (login, 404, onboarding, admin): the width is not used.
4. **Equal weight everywhere:** grids of identical cards on the landing page, dashboard and admin overview.
5. **Small, grey supporting text** (12-13 px) carries important information (privacy, strength, rules).
6. **Tables are wider than their cards** on the admin pages at 1280 px.
7. **Little feedback:** no undo, no drafts, no progress, toasts that cover the form on phones.
`;

if (hasAfter) {
  const below = SCREENS.flatMap((s) => [[s, 1280, s.after[0]], [s, 360, s.after[1]]]).filter(([, , scores]) => Math.min(...scores) < 9);
  md += `
## After: design v3 (Batch 4)

Average **${avg(SCREENS.map((s) => s.after.flat()))}**, lowest single score **${min(SCREENS.map((s) => s.after.flat()))}**.

${table('after')}

| Criterion | Average before | Average after | Lowest after |
|---|---:|---:|---:|
${CRITERIA.map((c, i) => {
    const b = SCREENS.flatMap((s) => [s.before[0][i], s.before[1][i]]);
    const a = SCREENS.flatMap((s) => [s.after[0][i], s.after[1][i]]);
    return `| ${c} | ${(b.reduce((x, y) => x + y, 0) / b.length).toFixed(1)} | ${(a.reduce((x, y) => x + y, 0) / a.length).toFixed(1)} | ${Math.min(...a)} |`;
  }).join('\n')}

${below.length === 0 ? 'Every score is 9 or higher.' : `**Not yet at 9** (${below.length} rows):\n\n${below.map(([s, w, scores]) => `- ${s.name} at ${w} px: ${CRITERIA.filter((_, i) => scores[i] < 9).map((c) => `${c} ${scores[CRITERIA.indexOf(c)]}`).join(', ')}${s.afterNote ? ` — ${s.afterNote}` : ''}`).join('\n')}`}

### What changed on each screen

${SCREENS.map((s) => `**${s.name}:** ${s.changes ?? '—'}`).join('\n\n')}
`;
} else {
  md += `
## After: design v3

Not scored yet: this section is added when the redesign is finished and the screens are captured again.
`;
}

writeFileSync(resolve(here, '..', 'design', '07-critique-v2.md'), md);
console.log(`07-critique-v2.md written (${SCREENS.length} screens, after scores: ${hasAfter ? 'yes' : 'not yet'})`);
