// Writes docs/i18n/REVIEW-BATCH-5.md: the NEW Batch 5 texts only (audio help, voice typing, picture
// names), key by key with English, Urdu and Roman Urdu side by side, for the team to check (D-031).
// These texts are SPOKEN: the Urdu and the Roman Urdu of one key must say the same thing, because
// Roman Urdu users hear the Urdu audio. Run in .\frontend:  node scripts/i18n-review-batch5.mjs
import { writeFileSync } from 'node:fs';
import en from '../src/i18n/dictionaries/en.js';
import ur from '../src/i18n/dictionaries/ur.js';
import urLatn from '../src/i18n/dictionaries/ur-Latn.js';
import { flattenKeys, lookup } from '../src/i18n/translate.js';
import { LANGUAGES } from '../src/i18n/languages.js';

const cell = (v) => (v === undefined || v === null ? '—' : String(v).replace(/\|/g, ' / ').replace(/\n/g, ' '));
const keys = flattenKeys({ assist: en.assist, help: en.help });
const groups = [
  ['Language chooser (in `i18n/languages.js`; heard before any language is chosen)', null],
  ['Page help (`help.screen.*`): the round button in the corner', 'help.screen.'],
  ['Field help (`help.field.*`): Listen under each box', 'help.field.'],
  ['Picture names (`help.option.*`): the small speaker on each picture', 'help.option.'],
  ['Help Centre guides and the voice check page (`help.centre.*`, `help.voiceCheck.*`, `help.notification`)', 'help.c|help.v|help.n'],
  ['Buttons, menu and messages (`assist.*`)', 'assist.'],
];
const out = [
  '# Batch 5 texts for team review',
  '',
  'Generated by `node scripts/i18n-review-batch5.mjs` (in `.\\frontend`) from the dictionaries. Every text',
  'below is a **draft** written by Claude Code until a team member who reads Urdu has checked it (D-031).',
  '',
  'Please check that each text:',
  '- is everyday Urdu a labourer uses, with no English technical words (no "field", "form", "submit");',
  '- is short enough to be spoken (about 20 words at most): one instruction, then one example;',
  '- says the **same thing** in Urdu and Roman Urdu: Roman Urdu users hear the Urdu audio;',
  '- matches what the screen shows (button names, the order of the steps).',
  '',
  'After a change, run `node scripts/i18n-review-batch5.mjs` again, and record the clip again if it was',
  'already recorded (`docs/audio/RECORDING-GUIDE.md`).',
];
let total = 0;
for (const [title, prefix] of groups) {
  out.push('', `## ${title}`, '', '| Key | English | اردو (Urdu) | Roman Urdu | Checked by |', '|---|---|---|---|---|');
  if (!prefix) {
    for (const l of LANGUAGES) {
      out.push(`| \`help.chooser.${l.code}\` (spoken) | ${cell(l.code === 'en' ? l.chooserSpoken : `Press here for ${l.code === 'ur' ? 'Urdu' : 'Roman Urdu'}.`)} | ${l.code === 'en' ? '—' : cell(l.chooserSpoken)} | ${l.code === 'ur-Latn' ? '(spoken in Urdu, see the Urdu column)' : '—'} | |`);
      const words = cell(`${l.chooserListen} / ${l.chooserNoVoice}`);
      out.push(`| \`chooserListen\` / \`chooserNoVoice\` (${l.code}) | ${l.code === 'en' ? words : '—'} | ${l.code === 'ur' ? words : '—'} | ${l.code === 'ur-Latn' ? words : '—'} | |`);
      total += 2;
    }
    continue;
  }
  const prefixes = prefix.split('|');
  for (const key of keys.filter((k) => prefixes.some((p) => k.startsWith(p)))) {
    out.push(`| \`${key}\` | ${cell(lookup(en, key))} | ${cell(lookup(ur, key))} | ${cell(lookup(urLatn, key))} | |`);
    total += 1;
  }
}
out.splice(2, 0, `${total} rows. Date: ${new Date().toISOString().slice(0, 10)}.`, '');
writeFileSync(new URL('../../docs/i18n/REVIEW-BATCH-5.md', import.meta.url), `${out.join('\n')}\n`);
console.log(`REVIEW-BATCH-5.md: ${total} rows`);
