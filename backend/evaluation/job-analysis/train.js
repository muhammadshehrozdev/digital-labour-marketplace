// Module 6: trains the naive Bayes classifier on the DEVELOPMENT file (protocol step 4).
// Run in ./backend:
//   npm run jobs:train -- --file <dev.csv> [--label category|task_type] [--cv] [--alpha 1 --ngram 1 --min-df 2]
//                         --out <model.json> [--format json|js]
//
//   --cv         the stratified 5-fold grid of 7.5 on this file only; prints the table and the chosen parameters,
//                then trains on the whole file with them
//   --format js  an ES module (export default {...}) for config/jobModel.generated.js, so Vercel bundles it
// With --format json the twin model without spelling variants (<name>.no-variants.json, same parameters) is written
// too: the evaluation's nb_no_variants system. Privacy: the writer refuses minDf < 2 and prints the vocabulary size and
// the 30 rarest kept features, so a person can check that no name or place slipped in.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadJobDataset } from './dataset.js';
import { crossValidate, examplesFor } from './cv.js';
import { train, checkModelForDisk, labelsWithoutData, features, DEFAULT_PARAMS } from '../../services/jobAnalyzer/naiveBayes.js';

const f3 = (x) => x.toFixed(3);

export function rarestFeatures(model, examples, count = 30) {
  const df = new Map();
  for (const e of examples) for (const f of new Set(features(e.text, { ngram: model.params.ngram, variants: model.tokenizer.variants }))) df.set(f, (df.get(f) ?? 0) + 1);
  return model.vocab.map((f) => ({ feature: f, documents: df.get(f) ?? 0 })).sort((a, b) => a.documents - b.documents || (a.feature < b.feature ? -1 : 1)).slice(0, count);
}

export const moduleText = (model) => `// Generated by npm run jobs:train -- --format js (Module 6). Do not edit: the modelId would no longer match.\n// Trained on ${model.trainedOn.file} (${model.trainedOn.items} items, sha256 ${model.trainedOn.sha256}), synthetic: ${model.trainedOn.synthetic}.\nexport default ${JSON.stringify(model)};\n`;

export function runTraining({ file, label = 'category', cv = false, params = {}, out, format = 'json' }) {
  const data = loadJobDataset(file);
  const examples = examplesFor(data.items, label);
  if (examples.length === 0) throw new Error(`No usable items for label ${label}`);
  const report = { synthetic: data.synthetic, file: data.file, sha256: data.sha256, items: data.items.length, examples: examples.length, label, cv: null };
  let chosen = { ...DEFAULT_PARAMS, ...params };
  if (cv) {
    report.cv = crossValidate(examples, { label });
    chosen = report.cv.chosen;
  }
  const trainedOn = { file: data.file, sha256: data.sha256, synthetic: data.synthetic };
  const model = checkModelForDisk(train(examples, { label, ...chosen, trainedOn }));
  const written = [];
  if (out) {
    if (format === 'js') writeFileSync(out, moduleText(model));
    else writeFileSync(out, `${JSON.stringify(model, null, 2)}\n`);
    written.push(out);
    if (format === 'json') {
      const twin = checkModelForDisk(train(examples, { label, ...chosen, variants: false, trainedOn }));
      const twinPath = out.replace(/\.json$/i, '') + '.no-variants.json';
      writeFileSync(twinPath, `${JSON.stringify(twin, null, 2)}\n`);
      written.push(twinPath);
    }
  }
  return { report, model, written, rare: rarestFeatures(model, examples), unseen: labelsWithoutData(model) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const arg = (n) => { const i = argv.indexOf(`--${n}`); return i === -1 ? undefined : argv[i + 1]; };
  const num = (n) => (arg(n) === undefined ? undefined : Number(arg(n)));
  if (!arg('file')) {
    console.error('Usage: npm run jobs:train -- --file <dev.csv> [--label category|task_type] [--cv] [--alpha --ngram --min-df] --out <model.json> [--format json|js]');
    process.exit(1);
  }
  try {
    const params = Object.fromEntries(Object.entries({ alpha: num('alpha'), ngram: num('ngram'), minDf: num('min-df') }).filter(([, v]) => v !== undefined));
    const { report, model, written, rare, unseen } = runTraining({ file: arg('file'), label: arg('label') ?? 'category', cv: argv.includes('--cv'), params, out: arg('out'), format: arg('format') ?? 'json' });
    if (report.synthetic) console.log('\n*** SYNTHETIC DATA: this model and these numbers only test the script. Never report them. ***\n');
    console.log(`File ${report.file} (${report.items} items; ${report.examples} used for label ${report.label}; sha256 ${report.sha256.slice(0, 12)}…)`);
    if (report.cv) {
      console.log(`\nCross-validation: ${report.cv.folds} folds, seed ${report.cv.seed}`);
      console.log('  alpha ngram minDf   mean macro-F1   per fold');
      for (const r of report.cv.rows) console.log(`  ${String(r.alpha).padEnd(5)} ${String(r.ngram).padEnd(5)} ${String(r.minDf).padEnd(5)}   ${f3(r.meanMacroF1)}           ${r.foldMacroF1.map(f3).join(' ')}`);
      if (report.cv.classesInFewerFolds.length) console.log(`  classes in fewer than ${report.cv.folds} folds: ${report.cv.classesInFewerFolds.map((c) => `${c.label} (${c.folds})`).join(', ')}`);
    }
    console.log(`\nChosen parameters: alpha ${model.params.alpha}, ngram ${model.params.ngram}, minDf ${model.params.minDf}`);
    console.log(`Model ${model.modelId}: ${model.labels.length} labels, vocabulary ${model.vocab.length} features`);
    if (unseen.length) console.log(`Labels with no training item (never predicted): ${unseen.join(', ')}`);
    console.log(`The 30 rarest kept features (check that no name or place slipped in):\n  ${rare.map((r) => `${r.feature} (${r.documents})`).join(', ')}`);
    for (const path of written) console.log(`Written: ${path}`);
  } catch (err) {
    console.error(`Training failed: ${err.message}`);
    process.exit(1);
  }
}
